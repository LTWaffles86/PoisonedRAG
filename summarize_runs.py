"""Collect experiments/runs/*/summary.json into result tables and the KB-size figure.

Writes experiments/results.md (also printed), report/results_table.tex and
report/fig_f1_vs_kb_size.{pdf,png}. Runs are keyed by their arguments, not their names.
"""
import glob
import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from retriever_mvp import FULL_CORPUS_SIZE  # noqa: E402

DATASETS = ["nq", "hotpotqa", "msmarco"]
DATASET_NAMES = {"nq": "NQ (Wikipedia)", "hotpotqa": "HotpotQA (Wikipedia)", "msmarco": "MS-MARCO (web)"}
RETRIEVERS = ["contriever", "ance", "gte-small"]
RETRIEVER_NAMES = {"contriever": "Contriever", "ance": "ANCE", "gte-small": "gte-small"}
COLORS = {"contriever": "#2a78d6", "ance": "#eb6834", "gte-small": "#1baf7a"}  # validated (dataviz), fixed order
MARKERS = {"contriever": "o", "ance": "s", "gte-small": "^"}


def load_runs():
    """{(dataset, retriever, kb_size, n_targets): {"attack": metrics, "clean": metrics}}"""
    runs = {}
    for path in sorted(glob.glob("experiments/runs/*/summary.json")):
        s = json.load(open(path))
        a = s["args"]
        key = (a["dataset"], a["retriever"], s["knowledge_base_size"], s["metrics"]["n_targets"])
        kind = "clean" if a["attack"] == "none" else "attack"
        runs.setdefault(key, {})[kind] = s["metrics"]
    return runs


def size_label(dataset, size):
    if size == FULL_CORPUS_SIZE[dataset]:
        return f"full ({size / 1e6:.2f}M)"
    return f"{size // 1000}k"


def rows(runs, dataset, n_targets=30):
    out = []
    for r in RETRIEVERS:
        for size in sorted(k[2] for k in runs if k[0] == dataset and k[1] == r and k[3] == n_targets):
            pair = runs[(dataset, r, size, n_targets)]
            att, cln = pair.get("attack"), pair.get("clean")
            out.append({
                "retriever": r, "size": size, "label": size_label(dataset, size),
                "f1": att and att["f1"], "hit": att and att["poison_retrieval_hit_rate"],
                "clean_hit": cln and cln["clean_hit_rate"], "clean_hit_attacked": att and att["clean_hit_rate"],
                "clean_f1": cln and cln["f1"],
            })
    return out


def fmt(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def write_markdown(runs):
    lines = ["# Retriever results (30 target questions per run, top-5, N=5 attack texts per target)", "",
             "Generated by `summarize_runs.py` from `experiments/runs/*/summary.json`. Do not edit by hand.", ""]
    for d in DATASETS:
        rs = rows(runs, d)
        if not rs:
            continue
        lines += [f"## {DATASET_NAMES[d]}", "",
                  "| Retriever | KB size | Attack F1 | Poison hit rate | Clean hit rate, no attack | Clean hit rate, attacked | Clean-run F1 |",
                  "|---|---|---|---|---|---|---|"]
        lines += [f"| {RETRIEVER_NAMES[r['retriever']]} | {r['label']} | {fmt(r['f1'])} | {fmt(r['hit'], 2)} | "
                  f"{fmt(r['clean_hit'], 2)} | {fmt(r['clean_hit_attacked'], 2)} | {fmt(r['clean_f1'], 1)} |" for r in rs]
        lines.append("")
    rep = [(d, r) for d in DATASETS for r in rows(runs, d, n_targets=100)]
    if rep:
        lines += ["## 100-target replications (paper setting)", "",
                  "| Dataset | Retriever | KB size | Attack F1 | Poison hit rate |", "|---|---|---|---|---|"]
        lines += [f"| {DATASET_NAMES[d]} | {RETRIEVER_NAMES[r['retriever']]} | {r['label']} | {fmt(r['f1'])} | {fmt(r['hit'], 2)} |"
                  for d, r in rep]
        lines.append("")
    text = "\n".join(lines)
    with open("experiments/results.md", "w") as f:
        f.write(text)
    print(text)


def write_latex(runs):
    lines = [r"% Generated by summarize_runs.py; needs \usepackage{booktabs}",
             r"\begin{tabular}{llrrrr}", r"\toprule",
             r"Dataset & Retriever / KB size & Attack F1 & Poison hit & Clean hit (no attack) & Clean hit (attacked) \\",
             r"\midrule"]
    for i, d in enumerate(DATASETS):
        rs = rows(runs, d)
        if not rs:
            continue
        if i:
            lines.append(r"\midrule")
        for j, r in enumerate(rs):
            name = DATASET_NAMES[d] if j == 0 else ""
            lines.append(f"{name} & {RETRIEVER_NAMES[r['retriever']]}, {r['label']} & {fmt(r['f1'])} & "
                         f"{fmt(r['hit'], 2)} & {fmt(r['clean_hit'], 2)} & {fmt(r['clean_hit_attacked'], 2)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    os.makedirs("report", exist_ok=True)
    with open("report/results_table.tex", "w") as f:
        f.write("\n".join(lines))


def plot(runs):
    datasets = [d for d in DATASETS if rows(runs, d)]
    fig, axes = plt.subplots(2, len(datasets), figsize=(3.2 * len(datasets), 5.2), sharex="col", squeeze=False)
    for c, d in enumerate(datasets):
        rs = rows(runs, d)
        for row, (key, ylabel) in enumerate([("f1", "Attack F1 (poison retrieval)"),
                                             ("clean_hit", "Clean hit rate, no attack")]):
            ax = axes[row][c]
            for r in RETRIEVERS:
                pts = [(x["size"], x[key]) for x in rs if x["retriever"] == r and x[key] is not None]
                if pts:
                    ax.plot(*zip(*pts), color=COLORS[r], marker=MARKERS[r], markersize=6, linewidth=2,
                            label=RETRIEVER_NAMES[r])
            ax.set_xscale("log")
            ax.set_ylim(-0.02 if row else 0.78, 1.02)
            ax.grid(True, color="#e5e5e2", linewidth=0.8)
            ax.set_axisbelow(True)
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            ax.axvline(FULL_CORPUS_SIZE[d], color="#9a9a96", linewidth=1, linestyle=":")
            if row == 0:
                ax.set_title(DATASET_NAMES[d], fontsize=10)
                ax.text(FULL_CORPUS_SIZE[d], 0.79, " full corpus", color="#6b6b67", fontsize=7, rotation=90,
                        ha="right", va="bottom")
            else:
                ax.set_xlabel("KB size (docs, log scale)")
            if c == 0:
                ax.set_ylabel(ylabel)
    legend = {}
    for ax in axes.flat:
        legend.update(zip(*reversed(ax.get_legend_handles_labels())))
    labels = [RETRIEVER_NAMES[r] for r in RETRIEVERS if RETRIEVER_NAMES[r] in legend]
    handles = [legend[name] for name in labels]
    fig.legend(handles, labels, loc="upper center", ncol=len(labels), frameon=False, bbox_to_anchor=(0.5, 1.0))
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    for ext in ("pdf", "png"):
        fig.savefig(f"report/fig_f1_vs_kb_size.{ext}", dpi=200)


if __name__ == "__main__":
    runs = load_runs()
    write_markdown(runs)
    write_latex(runs)
    plot(runs)
    print("Wrote experiments/results.md, report/results_table.tex, report/fig_f1_vs_kb_size.{pdf,png}")
